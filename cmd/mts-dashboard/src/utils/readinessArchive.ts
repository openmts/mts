export function buildReadinessArchive(input: ReadinessArchiveInput): ReadinessArchivePayload {
  const archived_at = input.now ?? new Date().toISOString()
  const locale: LocaleCode = input.locale === 'en' ? 'en' : 'zh'
  const productionDone = completedIds(input.state.production).sort()
  const edgeDone = completedIds(input.state.edgeHttps).sort()
  const scheduleDone = completedIds(input.state.backupSchedule).sort()
  return {
    version: 1,
    kind: 'mts.readiness.archive',
    archived_at,
    operator: (input.operator ?? '').trim() || 'unknown',
    note: (input.note ?? '').trim(),
    locale,
    score: { ...input.score, reasons: [...input.score.reasons] },
    doctor: {
      loaded: input.doctor.loaded,
      ok: input.doctor.ok,
      http_tls_enabled: input.doctor.http_tls_enabled ?? null,
      warn_count: input.doctor.warn_count ?? 0,
      checks: (input.doctor.checks ?? []).map((c) => ({ ...c })),
      error: input.doctor.error,
    },
    checklist: {
      production: productionDone,
      edgeHttps: edgeDone,
      backupSchedule: scheduleDone,
    },
    catalog: {
      production: productionCatalog(productionDone, locale),
      edgeHttps: edgeHttpsCatalog(edgeDone, locale),
      backupSchedule: backupScheduleCatalog(scheduleDone, locale),
    },
    state: {
      production: { ...input.state.production },
      edgeHttps: { ...input.state.edgeHttps },
      backupSchedule: { ...input.state.backupSchedule },
      updatedAt: input.state.updatedAt,
    },
  }
}

function formatCatalogSection(
  label: string,
  items: CatalogItem[],
  locale: LocaleCode,
): string[] {
  const t = copy[locale]
  const lines = [`### ${label}`, '']
  for (const item of items) {
    const mark = item.done ? t.done : t.open
    lines.push(`- [${mark}] ${item.id} — ${item.title}`)
    lines.push(`  - ${item.detail}`)
  }
  if (!items.length) lines.push('- —')
  lines.push('')
  return lines
}

export function formatReadinessArchiveMarkdown(a: ReadinessArchivePayload): string {
  const locale: LocaleCode = a.locale === 'en' ? 'en' : 'zh'
  const t = copy[locale]
  const sep = locale === 'zh' ? '：' : ': '
  const lines: string[] = [
    t.title,
    '',
    `- ${t.time}${sep}${a.archived_at}`,
    `- ${t.operator}${sep}${a.operator}`,
    `- ${t.score}${sep}${a.score.total}%`,
    `- ${t.parts}${sep}${t.checklistPart} ${a.score.checklist}% / HTTPS ${a.score.edgeHttps}% / ${t.backupPart} ${a.score.backupSchedule}% / Doctor ${a.score.doctor}%`,
  ]
  if (a.score.reasons.length) {
    lines.push(`- ${t.reasons}${sep}${a.score.reasons.join(', ')}`)
  }
  if (a.note) {
    lines.push(`- ${t.note}${sep}${a.note}`)
  }
  lines.push('', t.doctor, '')
  if (!a.doctor.loaded) {
    lines.push(`- ${t.notLoaded}${a.doctor.error ? `${sep}${a.doctor.error}` : ''}`)
  } else {
    lines.push(`- ok: ${a.doctor.ok === true ? 'yes' : 'no'}`)
    lines.push(`- http_tls_enabled: ${String(a.doctor.http_tls_enabled)}`)
    lines.push(`- warn_count: ${a.doctor.warn_count ?? 0}`)
    for (const c of a.doctor.checks ?? []) {
      lines.push(`- [${c.level}] ${c.code}: ${c.message}`)
    }
  }
  lines.push('', t.completed, '')
  lines.push(`- production: ${a.checklist.production.join(', ') || '—'}`)
  lines.push(`- edgeHttps: ${a.checklist.edgeHttps.join(', ') || '—'}`)
  lines.push(`- backupSchedule: ${a.checklist.backupSchedule.join(', ') || '—'}`)
  lines.push('', t.catalog, '')
  lines.push(...formatCatalogSection('production', a.catalog.production, locale))
  lines.push(...formatCatalogSection('edgeHttps', a.catalog.edgeHttps, locale))
  lines.push(...formatCatalogSection('backupSchedule', a.catalog.backupSchedule, locale))
  lines.push('---', '', t.footer, '')
  return lines.join('\n')
}

export function archiveFilenames(at = new Date()): { json: string; md: string } {
  const stamp = at.toISOString().replace(/[:.]/g, '-').slice(0, 19)
  return {
    json: `mts-readiness-archive-${stamp}.json`,
    md: `mts-readiness-archive-${stamp}.md`,
  }
}
