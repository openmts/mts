export interface DoctorArchiveSummary {
  loaded: boolean
  ok?: boolean
  http_tls_enabled?: boolean | null
  warn_count?: number
  checks?: { level: string; code: string; message: string }[]
  error?: string
}

export interface ReadinessArchiveInput {
  operator?: string
  note?: string
  state: ReadinessState
  score: ReadinessScoreBreakdown
  doctor: DoctorArchiveSummary
  now?: string
  /** 导出文案语言；默认 zh */
  locale?: LocaleCode
  /** 可选：降采样 statuses 摘要（只读归档） */
  downsample_status_summary?: DownsampleStatusSummaryInput | null
  /** 可选：密码策略 + 会话校准交接摘要 */
  commercial_handoff?: CommercialHandoffSummary | null
  /** 构造会话校准摘要用（未传 commercial_handoff 时） */
  session_expires_at?: string | null
  session_remaining_seconds?: number | null
  session_checked_at_ms?: number | null
  session_server_time_unix?: number | null
}

export interface ReadinessArchivePayload {
  version: 1
  kind: 'mts.readiness.archive'
  archived_at: string
  operator: string
  note: string
  locale: LocaleCode
  score: ReadinessScoreBreakdown
  doctor: DoctorArchiveSummary
  /** 已完成项 id（稳定、机器可读） */
  checklist: {
    production: string[]
    edgeHttps: string[]
    backupSchedule: string[]
  }
  /** 全量清单条目（title/detail 已按 locale 解析） */
  catalog: {
    production: CatalogItem[]
    edgeHttps: CatalogItem[]
    backupSchedule: CatalogItem[]
  }
  state: ReadinessState
  /** 部署材料包索引（与验收包对齐） */
  deploy_kit: DeployKitSummary
  /** 本地提醒勾选 id（不代表部署验收完成） */
  deploy_kit_local_hints: string[]
  /** 部署侧人工签核证据备注（自由文本；不计入评分） */
  signoff_notes: SignoffNotes
  /** 导出前预检摘要（与验收包对齐；不计分） */
  export_preflight: {
    warn_count: number
    info_count: number
    ok_count: number
    items: Pick<ExportPreflightItem, 'id' | 'level' | 'message' | 'target'>[]
  }
  /** 可选：降采样健康摘要（/admin/downsample/statuses summary） */
  downsample_status_summary?: Required<DownsampleStatusSummaryInput> | null
  /** 可选：密码策略与会话校准（可商用交接） */
  commercial_handoff?: CommercialHandoffSummary | null
}

