/** 就绪/演练归档模板（JSON + Markdown），供运维交接下载 */

import type { ReadinessScoreBreakdown } from './readinessScore.ts'
import type { ReadinessState } from './readinessState.ts'
import { completedIds } from './readinessState.ts'
import type { LocaleCode } from './localizedText.ts'
import {
  backupScheduleCatalog,
  edgeHttpsCatalog,
  productionCatalog,
  type CatalogItem,
} from './checklistCatalog.ts'

export interface DoctorArchiveSummary {
  loaded: boolean
  ok?: boolean
  http_tls_enabled?: boolean | null
  warn_count?: number
  checks?: { level: string; code: string; message: string }[]
  error?: string
}

export interface ReadinessArchiveInput {
  operator?: string
  note?: string
  state: ReadinessState
  score: ReadinessScoreBreakdown
  doctor: DoctorArchiveSummary
  now?: string
  /** 导出文案语言；默认 zh */
  locale?: LocaleCode
}

export interface ReadinessArchivePayload {
  version: 1
  kind: 'mts.readiness.archive'
  archived_at: string
  operator: string
  note: string
  locale: LocaleCode
  score: ReadinessScoreBreakdown
  doctor: DoctorArchiveSummary
  /** 已完成项 id（稳定、机器可读） */
  checklist: {
    production: string[]
    edgeHttps: string[]
    backupSchedule: string[]
  }
  /** 全量清单条目（title/detail 已按 locale 解析） */
  catalog: {
    production: CatalogItem[]
    edgeHttps: CatalogItem[]
    backupSchedule: CatalogItem[]
  }
  state: ReadinessState
}

