export const ACCEPTANCE_PACK_KIND = 'mts.acceptance.pack' as const
export const ACCEPTANCE_PACK_VERSION = 2 as const

export interface ServerVersionInfo {
  version: string
  commit?: string
  built_at?: string
}

export interface AcceptancePackInput {
  archive: ReadinessArchivePayload
  client: ClientBuildInfo
  server?: ServerVersionInfo | null
  opsActions?: OpsActionEntry[]
  operator?: string
  note?: string
  now?: string
  /** 若省略则继承 archive.locale */
  locale?: LocaleCode
  /** 可选覆盖；默认按 locale 生成部署材料包摘要 */
  deployKit?: DeployKitSummary
}

export interface AcceptancePackPayload {
  version: typeof ACCEPTANCE_PACK_VERSION
  kind: typeof ACCEPTANCE_PACK_KIND
  exported_at: string
  operator: string
  note: string
  locale: LocaleCode
  disclaimer: string
  client: ClientBuildInfo
  server: ServerVersionInfo | null
  readiness: ReadinessArchivePayload
  ops_actions: OpsActionEntry[]
  /** 部署材料包索引（不含样例全文，避免验收包过大） */
  deploy_kit: DeployKitSummary
  /** 签核备注完整性（来自归档 state.signoffNotes；不计入评分） */
  signoff_completeness: {
    filled: SignoffNoteField[]
    missing: SignoffNoteField[]
    complete: boolean
    filled_count: number
    total: number
    filled_labels: string[]
    missing_labels: string[]
  }
  /** 导出前预检摘要（不计分；不代表验收完成） */
  export_preflight: {
    warn_count: number
    info_count: number
    ok_count: number
    items: Pick<ExportPreflightItem, 'id' | 'level' | 'message' | 'target'>[]
  }
  /** 数据面契约快照（顶层机器可读；与 commercial_handoff.data_contract 对齐） */
  data_contract: AcceptanceDataContractSummary
}

